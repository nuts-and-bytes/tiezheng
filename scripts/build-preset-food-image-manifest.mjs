import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { PRESET_FOOD_IMAGE_PROVENANCE } from './preset-food-image-provenance.mjs';

const MAX_BYTES = 35 * 1024;

const moduleUrl = new URL(import.meta.url);
if (moduleUrl.protocol !== 'file:') {
  throw new Error(`unexpected module URL: ${import.meta.url}`);
}
export const DEFAULT_REPOSITORY_ROOT = resolve(
  fileURLToPath(new URL('..', moduleUrl)),
);
export const DEFAULT_MANIFEST_OUTPUT = resolve(
  DEFAULT_REPOSITORY_ROOT,
  'src/data/presetFoodImageManifest.generated.ts',
);

export async function buildPresetFoodImageManifest({
  repositoryRoot = DEFAULT_REPOSITORY_ROOT,
  output = resolve(repositoryRoot, 'src/data/presetFoodImageManifest.generated.ts'),
  provenance = PRESET_FOOD_IMAGE_PROVENANCE,
} = {}) {
  const provenanceRows = provenance.map((row) => Object.freeze({ ...row }));
  const expectedCount = PRESET_FOOD_IMAGE_PROVENANCE.length;
  if (expectedCount !== 33) {
    throw new Error('preset provenance must contain exactly 33 rows');
  }

  if (provenanceRows.length !== expectedCount) {
    throw new Error(`preset provenance must contain exactly ${expectedCount} rows`);
  }

  if (
    new Set(provenanceRows.map((row) => row.foodId)).size !== expectedCount ||
    new Set(provenanceRows.map((row) => row.path)).size !== expectedCount
  ) {
    throw new Error('preset food IDs and asset paths must be unique');
  }

  if (provenanceRows.some((row) => row.reviewed !== true)) {
    throw new Error('every preset provenance row must be explicitly reviewed');
  }

  const rows = [];

  for (const provenanceRow of provenanceRows) {
    if (typeof provenanceRow.path !== 'string') {
      throw new Error('preset asset path must be a string');
    }

    const relativePath = provenanceRow.path.replace(/^\//, '');

    if (!relativePath.startsWith('food-presets/') || relativePath.includes('..')) {
      throw new Error(`unsafe preset path: ${provenanceRow.path}`);
    }

    const bytes = await readFile(resolve(repositoryRoot, 'public', relativePath));

    if (bytes.length === 0 || bytes.length > MAX_BYTES) {
      throw new Error(`${provenanceRow.path} must be 1..${MAX_BYTES} bytes`);
    }

    if (
      bytes.subarray(0, 4).toString('ascii') !== 'RIFF' ||
      bytes.subarray(8, 12).toString('ascii') !== 'WEBP'
    ) {
      throw new Error(`${provenanceRow.path} is not a RIFF/WEBP file`);
    }

    const metadata = await sharp(bytes, { failOn: 'error' }).metadata();

    if (
      metadata.format !== 'webp' ||
      metadata.width !== provenanceRow.width ||
      metadata.height !== provenanceRow.height
    ) {
      throw new Error(
        `${provenanceRow.path} must be ${provenanceRow.width}x${provenanceRow.height} WebP`,
      );
    }

    rows.push({
      ...provenanceRow,
      sha256: createHash('sha256').update(bytes).digest('hex'),
    });
  }

  if (new Set(rows.map((row) => row.sha256)).size !== rows.length) {
    throw new Error('each preset requires different encoded image bytes');
  }

  const moduleSource =
    '// Generated by npm run food-assets:manifest. Do not edit by hand.\n' +
    `export const PRESET_FOOD_IMAGE_MANIFEST = ${JSON.stringify(rows, null, 2)} as const;\n\n` +
    'export type PresetFoodImageManifestRow = (typeof PRESET_FOOD_IMAGE_MANIFEST)[number];\n';

  await writeFile(output, moduleSource, 'utf8');
}

const invokedScript = process.argv[1];
if (
  invokedScript !== undefined &&
  pathToFileURL(resolve(invokedScript)).href === import.meta.url
) {
  await buildPresetFoodImageManifest();
}
